//! `roidota` - command-line client for the RoidOTA firmware update server.

mod api;
mod config;
mod output;

use std::io::{IsTerminal, Write};
use std::path::{Path, PathBuf};
use std::process::ExitCode;
use std::thread;
use std::time::{Duration, Instant};

use anyhow::{anyhow, bail, Context, Result};
use clap::{Args, Parser, Subcommand};
use serde::Serialize;
use serde_json::{json, Value};

use api::{Api, Deployment, Firmware};
use config::Config;

/// Exit code used when a command ran, but a deployment did not succeed.
const EXIT_DEPLOYMENT_FAILED: u8 = 2;

#[derive(Parser)]
#[command(name = "roidota", version, about, propagate_version = true)]
struct Cli {
    /// Base URL of the RoidOTA server [default: http://localhost:3000]
    #[arg(long, global = true, env = "ROIDOTA_URL", value_name = "URL")]
    url: Option<String>,

    /// API key of the server
    #[arg(
        long,
        global = true,
        env = "ROIDOTA_API_KEY",
        value_name = "KEY",
        hide_env_values = true
    )]
    api_key: Option<String>,

    /// Print machine-readable JSON instead of tables
    #[arg(long, global = true)]
    json: bool,

    /// HTTP request timeout in seconds
    #[arg(long, global = true, default_value_t = 30, value_name = "SECONDS")]
    timeout: u64,

    #[command(subcommand)]
    command: Command,
}

#[derive(Subcommand)]
enum Command {
    /// Check that the server and its dependencies are up
    Health,
    /// Manage firmware binaries
    #[command(subcommand)]
    Firmware(FirmwareCommand),
    /// Inspect and control devices
    #[command(subcommand)]
    Device(DeviceCommand),
    /// Deploy firmware to one or more devices
    Deploy {
        /// Firmware ID, `name@version`, or `name` (latest upload)
        firmware: String,
        /// Target device IDs
        #[arg(required = true)]
        devices: Vec<String>,
        #[command(flatten)]
        wait: WaitArgs,
    },
    /// Inspect deployments
    #[command(subcommand)]
    Deployment(DeploymentCommand),
    /// Show or change the saved server URL and API key
    #[command(subcommand)]
    Config(ConfigCommand),
}

#[derive(Args)]
struct WaitArgs {
    /// Wait until the devices report the result (exit code 2 on failure)
    #[arg(long)]
    wait: bool,
    /// Give up waiting after this many seconds
    #[arg(long, default_value_t = 330, value_name = "SECONDS")]
    wait_timeout: u64,
}

#[derive(Subcommand)]
enum FirmwareCommand {
    /// List uploaded firmware
    List,
    /// Upload a firmware binary
    Upload {
        /// Path to the compiled .bin file
        file: PathBuf,
        /// Firmware name [default: the file name without extension]
        #[arg(long)]
        name: Option<String>,
        /// Firmware version [default: generated by the server]
        #[arg(long = "fw-version", value_name = "VERSION")]
        fw_version: Option<String>,
        /// Deploy to these devices right after uploading (comma separated)
        #[arg(long, value_delimiter = ',', value_name = "DEVICES")]
        deploy_to: Vec<String>,
        #[command(flatten)]
        wait: WaitArgs,
    },
    /// Delete firmware that is not in use
    Delete {
        /// Firmware ID, `name@version`, or `name` (latest upload)
        firmware: String,
        /// Do not ask for confirmation
        #[arg(long, short)]
        yes: bool,
    },
}

#[derive(Subcommand)]
enum DeviceCommand {
    /// List registered devices
    List,
    /// Show live status (all devices, or one)
    Status { device: Option<String> },
    /// Show the firmware history of a device
    History { device: String },
    /// Restart a device
    Restart { device: String },
    /// Ask a device to send a heartbeat now
    Heartbeat { device: String },
    /// Send a custom command to a device
    Command {
        device: String,
        command: String,
        /// Command parameters as a JSON object
        #[arg(long, value_name = "JSON")]
        params: Option<String>,
    },
    /// Roll a device back to its previous firmware
    Rollback {
        device: String,
        #[command(flatten)]
        wait: WaitArgs,
    },
    /// Delete a device and its history
    Delete {
        device: String,
        /// Do not ask for confirmation
        #[arg(long, short)]
        yes: bool,
    },
}

#[derive(Subcommand)]
enum DeploymentCommand {
    /// List deployments, most recent first
    List {
        /// Only deployments that are still in flight
        #[arg(long)]
        pending: bool,
    },
    /// Show one deployment
    Show { id: String },
    /// Wait for deployments to finish (exit code 2 on failure)
    Wait {
        #[arg(required = true)]
        ids: Vec<String>,
        /// Give up waiting after this many seconds
        #[arg(long, default_value_t = 330, value_name = "SECONDS")]
        wait_timeout: u64,
    },
}

#[derive(Subcommand)]
enum ConfigCommand {
    /// Print the effective configuration
    Show,
    /// Save the server URL and/or API key
    Set {
        /// Server URL to save
        #[arg(long = "server-url", value_name = "URL")]
        server_url: Option<String>,
        /// API key to save
        #[arg(long = "key", value_name = "KEY")]
        key: Option<String>,
    },
    /// Print the location of the configuration file
    Path,
}

/// Everything a command needs to talk to the server and print results.
struct Context_ {
    api: Api,
    json: bool,
}

impl Context_ {
    /// Prints `value` as JSON, or runs the human-readable renderer.
    fn emit<T: Serialize>(&self, value: &T, human: impl FnOnce(&T)) -> Result<()> {
        if self.json {
            println!("{}", serde_json::to_string_pretty(value)?);
        } else {
            human(value);
        }
        Ok(())
    }
}

fn main() -> ExitCode {
    let cli = Cli::parse();
    match run(cli) {
        Ok(code) => code,
        Err(error) => {
            eprintln!("error: {error:#}");
            ExitCode::FAILURE
        }
    }
}

fn run(cli: Cli) -> Result<ExitCode> {
    let config_path = Config::path()?;
    let saved = Config::load(&config_path)?;

    if let Command::Config(command) = &cli.command {
        return run_config(command, &cli, saved, &config_path);
    }

    let url = cli
        .url
        .or(saved.url)
        .unwrap_or_else(|| "http://localhost:3000".to_string());
    let api_key = cli.api_key.or(saved.api_key).filter(|key| !key.is_empty());
    let ctx = Context_ {
        api: Api::new(&url, api_key, Duration::from_secs(cli.timeout))?,
        json: cli.json,
    };

    match cli.command {
        Command::Health => health(&ctx),
        Command::Firmware(command) => run_firmware(&ctx, command),
        Command::Device(command) => run_device(&ctx, command),
        Command::Deploy {
            firmware,
            devices,
            wait,
        } => deploy(&ctx, &firmware, &devices, &wait),
        Command::Deployment(command) => run_deployment(&ctx, command),
        Command::Config(_) => unreachable!("handled above"),
    }
}

// ------------------------------------------------------------------ config

fn run_config(
    command: &ConfigCommand,
    cli: &Cli,
    mut saved: Config,
    path: &Path,
) -> Result<ExitCode> {
    match command {
        ConfigCommand::Path => println!("{}", path.display()),
        ConfigCommand::Show => {
            let url = cli.url.clone().or(saved.url);
            let key = cli.api_key.clone().or(saved.api_key);
            if cli.json {
                let view = json!({
                    "path": path.display().to_string(),
                    "url": url,
                    "apiKeySet": key.is_some(),
                });
                println!("{}", serde_json::to_string_pretty(&view)?);
            } else {
                println!("config file: {}", path.display());
                println!(
                    "url:         {}",
                    url.as_deref().unwrap_or("http://localhost:3000 (default)")
                );
                println!(
                    "api key:     {}",
                    key.as_deref()
                        .map(config::mask)
                        .unwrap_or_else(|| "not set".into())
                );
            }
        }
        ConfigCommand::Set { server_url, key } => {
            if server_url.is_none() && key.is_none() {
                bail!("nothing to save: pass --server-url and/or --key");
            }
            if let Some(url) = server_url {
                // Validates the URL before it is written.
                Api::new(url, None, Duration::from_secs(1))?;
                saved.url = Some(url.trim().trim_end_matches('/').to_string());
            }
            if let Some(key) = key {
                saved.api_key = Some(key.clone());
            }
            saved.save(path)?;
            println!("Saved {}", path.display());
        }
    }
    Ok(ExitCode::SUCCESS)
}

// ------------------------------------------------------------------ health

fn health(ctx: &Context_) -> Result<ExitCode> {
    let report = ctx.api.health()?;
    let healthy = report.get("status").and_then(Value::as_str) == Some("ok");

    ctx.emit(&report, |report| {
        let text = |key: &str| {
            report
                .get(key)
                .and_then(Value::as_str)
                .unwrap_or(output::NONE)
        };
        println!(
            "{} {} - {}",
            text("service"),
            text("version"),
            text("status")
        );
        if let Some(checks) = report.get("checks").and_then(Value::as_object) {
            for (name, state) in checks {
                println!("  {name:<9} {}", state.as_str().unwrap_or(output::NONE));
            }
        }
    })?;
    Ok(if healthy {
        ExitCode::SUCCESS
    } else {
        ExitCode::FAILURE
    })
}

// ---------------------------------------------------------------- firmware

fn run_firmware(ctx: &Context_, command: FirmwareCommand) -> Result<ExitCode> {
    match command {
        FirmwareCommand::List => {
            let firmware = ctx.api.list_firmware()?;
            ctx.emit(&firmware, |firmware| {
                if firmware.is_empty() {
                    println!("No firmware uploaded yet.");
                    return;
                }
                let rows = firmware
                    .iter()
                    .map(|f| {
                        vec![
                            f.name.clone(),
                            f.version.clone(),
                            output::bytes(f.size),
                            output::timestamp(f.uploaded_at.as_deref()),
                            f.id.clone(),
                        ]
                    })
                    .collect();
                println!(
                    "{}",
                    output::table(&["NAME", "VERSION", "SIZE", "UPLOADED (UTC)", "ID"], rows)
                );
            })?;
        }
        FirmwareCommand::Upload {
            file,
            name,
            fw_version,
            deploy_to,
            wait,
        } => return upload(ctx, &file, name, fw_version, &deploy_to, &wait),
        FirmwareCommand::Delete { firmware, yes } => {
            let target = resolve_firmware(&ctx.api, &firmware)?;
            confirm(yes, &format!("Delete firmware {}?", target.label))?;
            let response = ctx.api.delete_firmware(&target.id)?;
            ctx.emit(&response, |_| println!("Deleted firmware {}", target.label))?;
        }
    }
    Ok(ExitCode::SUCCESS)
}

fn upload(
    ctx: &Context_,
    file: &Path,
    name: Option<String>,
    version: Option<String>,
    deploy_to: &[String],
    wait: &WaitArgs,
) -> Result<ExitCode> {
    let metadata =
        std::fs::metadata(file).with_context(|| format!("could not read {}", file.display()))?;
    if !metadata.is_file() {
        bail!("{} is not a file", file.display());
    }
    if metadata.len() == 0 {
        bail!("{} is empty", file.display());
    }

    let name = match name {
        Some(name) => name,
        None => file
            .file_stem()
            .and_then(|stem| stem.to_str())
            .map(str::to_string)
            .ok_or_else(|| {
                anyhow!("could not derive a firmware name from the file; pass --name")
            })?,
    };

    let result = ctx
        .api
        .upload_firmware(file, &name, version.as_deref(), deploy_to)?;
    let started: Vec<String> = result
        .deployment
        .iter()
        .flat_map(|batch| &batch.results)
        .filter_map(|r| r.value.as_ref().map(|v| v.deployment_id.clone()))
        .collect();
    let rejected = result.deployment.as_ref().map_or(0, |batch| batch.failed);

    ctx.emit(&result, |result| {
        let f = &result.firmware;
        println!(
            "Uploaded {} ({})",
            output::firmware(&f.name, &f.version),
            output::bytes(f.size)
        );
        println!("  id:     {}", f.id);
        println!("  md5:    {}", output::or_none(f.md5.as_deref()));
        println!("  sha256: {}", output::or_none(f.sha256.as_deref()));
        if let Some(batch) = &result.deployment {
            print_batch(batch);
        }
    })?;

    finish_deployments(ctx, &started, rejected, wait)
}

/// A firmware picked by ID or by name.
struct FirmwareTarget {
    id: String,
    label: String,
}

fn is_uuid(text: &str) -> bool {
    let bytes = text.as_bytes();
    bytes.len() == 36
        && bytes.iter().enumerate().all(|(index, byte)| match index {
            8 | 13 | 18 | 23 => *byte == b'-',
            _ => byte.is_ascii_hexdigit(),
        })
}

/// Picks a firmware from `available` (newest first) by ID, `name@version` or name.
fn pick_firmware<'a>(available: &'a [Firmware], reference: &str) -> Result<&'a Firmware> {
    if let Some(found) = available.iter().find(|f| f.id == reference) {
        return Ok(found);
    }
    if let Some((name, version)) = reference.rsplit_once('@') {
        return available
            .iter()
            .find(|f| f.name == name && f.version == version)
            .ok_or_else(|| anyhow!("no firmware named \"{name}\" with version \"{version}\""));
    }
    available
        .iter()
        .find(|f| f.name == reference)
        .ok_or_else(|| anyhow!("no firmware matches \"{reference}\" (see `roidota firmware list`)"))
}

fn resolve_firmware(api: &Api, reference: &str) -> Result<FirmwareTarget> {
    if is_uuid(reference) {
        return Ok(FirmwareTarget {
            id: reference.to_string(),
            label: reference.to_string(),
        });
    }
    let available = api.list_firmware()?;
    let found = pick_firmware(&available, reference)?;
    Ok(FirmwareTarget {
        id: found.id.clone(),
        label: output::firmware(&found.name, &found.version),
    })
}

// ----------------------------------------------------------------- devices

fn run_device(ctx: &Context_, command: DeviceCommand) -> Result<ExitCode> {
    match command {
        DeviceCommand::List => {
            let devices = ctx.api.list_devices()?;
            ctx.emit(&devices, |devices| {
                if devices.is_empty() {
                    println!("No devices registered yet.");
                    return;
                }
                let rows = devices
                    .iter()
                    .map(|d| {
                        vec![
                            d.device_id.clone(),
                            output::or_none(d.connection_status.as_deref()),
                            output::or_none(d.ip.as_deref()),
                            d.current_firmware
                                .as_ref()
                                .map_or(output::NONE.into(), |f| {
                                    output::firmware(&f.name, &f.version)
                                }),
                            output::timestamp(d.last_seen.as_deref()),
                        ]
                    })
                    .collect();
                println!(
                    "{}",
                    output::table(
                        &["DEVICE", "STATUS", "IP", "FIRMWARE", "LAST SEEN (UTC)"],
                        rows
                    )
                );
            })?;
        }
        DeviceCommand::Status { device } => {
            let statuses = match device {
                Some(device) => vec![ctx.api.device_status(&device)?],
                None => ctx.api.device_statuses()?,
            };
            ctx.emit(&statuses, |statuses| {
                if statuses.is_empty() {
                    println!("No devices have reported in yet.");
                    return;
                }
                let rows = statuses
                    .iter()
                    .map(|s| {
                        vec![
                            s.device_id.clone(),
                            s.status.clone(),
                            output::or_none(s.ip.as_deref()),
                            s.rssi
                                .map_or(output::NONE.into(), |rssi| format!("{rssi} dBm")),
                            output::uptime(s.uptime),
                            output::bytes(s.free_heap.map(|heap| heap as u64)),
                            s.current_firmware
                                .as_ref()
                                .map_or(output::NONE.into(), |f| {
                                    output::firmware(&f.name, &f.version)
                                }),
                            output::timestamp(s.last_seen.as_deref()),
                        ]
                    })
                    .collect();
                println!(
                    "{}",
                    output::table(
                        &[
                            "DEVICE",
                            "STATUS",
                            "IP",
                            "RSSI",
                            "UPTIME",
                            "FREE HEAP",
                            "FIRMWARE",
                            "LAST SEEN (UTC)"
                        ],
                        rows
                    )
                );
            })?;
        }
        DeviceCommand::History { device } => {
            let history = ctx.api.device_history(&device)?;
            ctx.emit(&history, |history| {
                if history.is_empty() {
                    println!("No deployments recorded for {device}.");
                    return;
                }
                let rows = history
                    .iter()
                    .map(|h| {
                        vec![
                            output::firmware(&h.firmware.name, &h.firmware.version),
                            h.status.clone(),
                            output::timestamp(h.applied_at.as_deref()),
                            output::timestamp(h.completed_at.as_deref()),
                            output::or_none(h.error_message.as_deref()),
                        ]
                    })
                    .collect();
                println!(
                    "{}",
                    output::table(
                        &[
                            "FIRMWARE",
                            "STATUS",
                            "STARTED (UTC)",
                            "FINISHED (UTC)",
                            "ERROR"
                        ],
                        rows
                    )
                );
            })?;
        }
        DeviceCommand::Restart { device } => send_command(ctx, &device, "restart", None)?,
        DeviceCommand::Heartbeat { device } => send_command(ctx, &device, "heartbeat", None)?,
        DeviceCommand::Command {
            device,
            command,
            params,
        } => {
            let params = params
                .map(|text| {
                    let value: Value =
                        serde_json::from_str(&text).context("--params is not valid JSON")?;
                    if !value.is_object() {
                        bail!("--params must be a JSON object, e.g. '{{\"level\": 3}}'");
                    }
                    Ok(value)
                })
                .transpose()?;
            send_command(ctx, &device, &command, params)?;
        }
        DeviceCommand::Rollback { device, wait } => {
            let started = ctx.api.rollback(&device)?;
            ctx.emit(&started, |started| {
                println!("{}", started.message);
                println!("  deployment: {}", started.deployment_id);
            })?;
            return finish_deployments(ctx, &[started.deployment_id], 0, &wait);
        }
        DeviceCommand::Delete { device, yes } => {
            confirm(yes, &format!("Delete device {device} and its history?"))?;
            let response = ctx.api.delete_device(&device)?;
            ctx.emit(&response, |_| println!("Deleted device {device}"))?;
        }
    }
    Ok(ExitCode::SUCCESS)
}

fn send_command(ctx: &Context_, device: &str, command: &str, params: Option<Value>) -> Result<()> {
    let response = ctx.api.send_command(device, command, params)?;
    ctx.emit(&response, |_| println!("Sent \"{command}\" to {device}"))
}

// ------------------------------------------------------------- deployments

fn deploy(ctx: &Context_, firmware: &str, devices: &[String], wait: &WaitArgs) -> Result<ExitCode> {
    let target = resolve_firmware(&ctx.api, firmware)?;

    let (started, rejected) = if let [device] = devices {
        let started = ctx.api.deploy(device, &target.id)?;
        ctx.emit(&started, |started| {
            println!("{}", started.message);
            println!("  deployment: {}", started.deployment_id);
        })?;
        (vec![started.deployment_id], 0)
    } else {
        let batch = ctx.api.deploy_batch(devices, &target.id)?;
        ctx.emit(&batch, print_batch)?;
        let started = batch
            .results
            .iter()
            .filter_map(|r| r.value.as_ref().map(|v| v.deployment_id.clone()))
            .collect();
        (started, batch.failed)
    };

    finish_deployments(ctx, &started, rejected, wait)
}

fn print_batch(batch: &api::BatchDeployment) {
    println!("{}", batch.message);
    for result in &batch.results {
        match (&result.value, &result.reason) {
            (Some(started), _) => println!(
                "  {:<24} started   {}",
                result.device_id, started.deployment_id
            ),
            (None, Some(reason)) => {
                println!("  {:<24} rejected  {}", result.device_id, reason.message)
            }
            (None, None) => println!("  {:<24} {}", result.device_id, result.status),
        }
    }
}

/// Common tail of every command that starts deployments: optionally wait for
/// them, and turn rejections or failures into exit code 2.
fn finish_deployments(
    ctx: &Context_,
    started: &[String],
    rejected: u32,
    wait: &WaitArgs,
) -> Result<ExitCode> {
    let mut failed = rejected > 0;
    if wait.wait && !started.is_empty() {
        let finished = wait_for(ctx, started, Duration::from_secs(wait.wait_timeout))?;
        failed |= finished.iter().any(|d| !d.succeeded());
    }
    Ok(if failed {
        ExitCode::from(EXIT_DEPLOYMENT_FAILED)
    } else {
        ExitCode::SUCCESS
    })
}

fn poll_interval() -> Duration {
    let millis = std::env::var("ROIDOTA_POLL_INTERVAL_MS")
        .ok()
        .and_then(|value| value.parse().ok())
        .unwrap_or(2000);
    Duration::from_millis(millis)
}

/// Polls until every deployment is finished or the timeout elapses, reporting
/// state changes on stderr. Returns the last known state of each deployment.
fn wait_for(ctx: &Context_, ids: &[String], timeout: Duration) -> Result<Vec<Deployment>> {
    let deadline = Instant::now() + timeout;
    let mut last_status: Vec<Option<String>> = vec![None; ids.len()];

    let deployments = loop {
        let mut current = Vec::with_capacity(ids.len());
        for (index, id) in ids.iter().enumerate() {
            let deployment = ctx.api.deployment(id)?;
            if last_status[index].as_deref() != Some(deployment.status.as_str()) {
                if !ctx.json {
                    let detail = deployment
                        .error_message
                        .as_deref()
                        .map(|message| format!(" ({message})"))
                        .unwrap_or_default();
                    eprintln!("{}: {}{}", deployment.device_id, deployment.status, detail);
                }
                last_status[index] = Some(deployment.status.clone());
            }
            current.push(deployment);
        }

        if current.iter().all(Deployment::is_finished) {
            break current;
        }
        if Instant::now() >= deadline {
            if !ctx.json {
                eprintln!("Gave up waiting after {}s", timeout.as_secs());
            }
            break current;
        }
        thread::sleep(poll_interval());
    };

    if ctx.json {
        println!("{}", serde_json::to_string_pretty(&deployments)?);
    }
    Ok(deployments)
}

fn deployment_rows(deployments: &[Deployment]) -> Vec<Vec<String>> {
    deployments
        .iter()
        .map(|d| {
            vec![
                d.device_id.clone(),
                output::firmware(&d.firmware.name, &d.firmware.version),
                d.status.clone(),
                output::timestamp(d.applied_at.as_deref()),
                output::or_none(d.error_message.as_deref()),
                d.id.clone(),
            ]
        })
        .collect()
}

const DEPLOYMENT_HEADERS: [&str; 6] = [
    "DEVICE",
    "FIRMWARE",
    "STATUS",
    "STARTED (UTC)",
    "ERROR",
    "ID",
];

fn run_deployment(ctx: &Context_, command: DeploymentCommand) -> Result<ExitCode> {
    match command {
        DeploymentCommand::List { pending: true } => {
            let pending = ctx.api.pending_deployments()?;
            ctx.emit(&pending, |pending| {
                if pending.is_empty() {
                    println!("No deployments in flight.");
                    return;
                }
                let rows = pending
                    .iter()
                    .map(|p| {
                        vec![
                            p.device_id.clone(),
                            output::firmware(&p.firmware.name, &p.firmware.version),
                            output::or_none(p.status.as_deref()),
                            output::timestamp(p.applied_at.as_deref()),
                            p.id.clone(),
                        ]
                    })
                    .collect();
                println!(
                    "{}",
                    output::table(
                        &["DEVICE", "FIRMWARE", "STATUS", "STARTED (UTC)", "ID"],
                        rows
                    )
                );
            })?;
        }
        DeploymentCommand::List { pending: false } => {
            let deployments = ctx.api.deployments()?;
            ctx.emit(&deployments, |deployments| {
                if deployments.is_empty() {
                    println!("No deployments yet.");
                } else {
                    println!(
                        "{}",
                        output::table(&DEPLOYMENT_HEADERS, deployment_rows(deployments))
                    );
                }
            })?;
        }
        DeploymentCommand::Show { id } => {
            let deployment = ctx.api.deployment(&id)?;
            ctx.emit(&deployment, |d| {
                println!(
                    "{}",
                    output::table(
                        &DEPLOYMENT_HEADERS,
                        deployment_rows(std::slice::from_ref(d))
                    )
                );
            })?;
        }
        DeploymentCommand::Wait { ids, wait_timeout } => {
            let finished = wait_for(ctx, &ids, Duration::from_secs(wait_timeout))?;
            if finished.iter().any(|d| !d.succeeded()) {
                return Ok(ExitCode::from(EXIT_DEPLOYMENT_FAILED));
            }
        }
    }
    Ok(ExitCode::SUCCESS)
}

